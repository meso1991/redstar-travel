const i18nConfig = {
    defaultLang: 'en'
};

function getCurrentLang() {
    const stored = localStorage.getItem('redstar_lang');
    if (stored) return stored;
    
    const htmlLang = document.documentElement.lang;
    if (htmlLang && ['en', 'ar'].includes(htmlLang)) return htmlLang;
    
    return 'en';
}

function setLanguage(lang) {
    if (!['en', 'ar'].includes(lang)) return;
    
    localStorage.setItem('redstar_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    
    applyTranslations();
    document.dispatchEvent(new CustomEvent('redstar:language-changed'));
}

function getTranslation(key, section = 'common') {
    const lang = getCurrentLang();
    const path = key.split('.');
    
    let obj = translations[section];
    if (!obj) obj = translations.common;
    
    for (const part of path) {
        obj = obj?.[part];
        if (!obj) break;
    }
    
    if (typeof obj === 'object' && obj[lang]) {
        return obj[lang];
    }
    
    return key;
}

function applyTranslations() {
    const page = document.body.dataset.page || 'index';
    const lang = getCurrentLang();
    
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const text = getTranslation(key, page);
        
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = text;
        } else if (el.tagName === 'OPTION') {
            el.textContent = text;
        } else {
            el.textContent = text;
        }
    });
    
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.dataset.i18nPlaceholder;
        const text = getTranslation(key, page);
        el.placeholder = text;
    });
    
    const yearEl = document.querySelector('[data-current-year]');
    if (yearEl) {
        yearEl.textContent = new Date().getFullYear();
    }
}

document.addEventListener('DOMContentLoaded', function() {
    applyTranslations();
    
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', function() {
            const lang = this.dataset.lang;
            setLanguage(lang);
            
            document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
            this.classList.add('active');
        });
    });
    
    const currentLang = getCurrentLang();
    document.querySelector(`[data-lang="${currentLang}"]`)?.classList.add('active');
});

function openTab(evt, tabName) {
    const tabContents = document.querySelectorAll('.tab-content');
    tabContents.forEach(tab => {
        tab.classList.remove('active');
    });
    
    const tabButtons = document.querySelectorAll('.tab-btn');
    tabButtons.forEach(btn => {
        btn.classList.remove('active');
    });
    
    const tabElement = document.getElementById(tabName);
    if (tabElement) {
        tabElement.classList.add('active');
    }
    
    if (evt && evt.currentTarget) {
        evt.currentTarget.classList.add('active');
    }
}

function toggleReturn(show) {
    const returnBox = document.getElementById('return-box');
    if (returnBox) {
        returnBox.hidden = !show;
        if (!show) {
            const returnInput = document.getElementById('flight-return');
            if (returnInput) returnInput.value = '';
        }
    }
}

function fillAirportField(fieldId, value) {
    const field = document.getElementById(fieldId);
    if (field) {
        field.value = value;
        field.focus();
    }
}

function buildUrl(page, params) {
    const url = new URL(page, window.location.origin);
    Object.entries(params).forEach(([key, value]) => {
        if (value) {
            url.searchParams.set(key, value);
        }
    });
    return url.toString();
}

function searchFlights() {
    const origin = document.getElementById('flight-origin')?.value.trim();
    const destination = document.getElementById('flight-dest')?.value.trim();
    const departure = document.getElementById('flight-departure')?.value;
    const returnDate = document.getElementById('flight-return')?.value;
    const adults = document.getElementById('adults')?.value || '1';
    const children = document.getElementById('kids')?.value || '0';
    const infants = document.getElementById('infants')?.value || '0';
    const cabin = document.getElementById('flight-cabin')?.value || 'economy';
    const currency = document.getElementById('flight-currency')?.value || 'USD';
    const isRoundTrip = !document.getElementById('return-box')?.hidden;

    if (!origin || !destination || !departure) {
        alert(document.documentElement.lang === 'ar' ? 'يرجى إدخال مدينة المغادرة والوجهة وتاريخ المغادرة.' : 'Please enter origin, destination, and departure date.');
        return;
    }

    if (isRoundTrip && !returnDate) {
        alert(document.documentElement.lang === 'ar' ? 'يرجى اختيار تاريخ العودة لرحلة الذهاب والعودة.' : 'Please choose a return date for a round trip.');
        return;
    }

    const searchUrl = buildUrl('results.html', {
        origin,
        destination,
        departureDate: departure,
        returnDate: isRoundTrip ? returnDate : '',
        adults,
        children,
        infants,
        cabin,
        currency
    });

    window.location.href = searchUrl;
}

function searchHotels() {
    const destination = document.getElementById('hotel-dest')?.value.trim();
    const checkin = document.getElementById('hotel-checkin')?.value;
    const checkout = document.getElementById('hotel-checkout')?.value;
    const guests = document.getElementById('guests')?.value || '2';
    const rooms = document.getElementById('rooms')?.value || '1';

    if (!destination || !checkin || !checkout) {
        alert(document.documentElement.lang === 'ar' ? 'يرجى إكمال الوجهة وتاريخ الدخول والخروج.' : 'Please complete destination, check-in, and check-out.');
        return;
    }

    const searchUrl = buildUrl('hotel-results.html', {
        destination,
        checkin,
        checkout,
        guests,
        rooms
    });

    window.location.href = searchUrl;
}

